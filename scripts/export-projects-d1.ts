/**
 * Export the bilingual project TOML files into an idempotent D1 seed SQL file.
 * Run: pnpm d1:export-projects
 *
 * This does not apply changes to D1. Review the generated SQL, then apply it
 * to the local database first. Production import must be an explicit operation.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'toml';
import type { Project, ProjectsData } from '../src/lib/types/Project';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const source = path.join(root, 'src/lib/data');
const output = path.join(root, 'migrations/0004_projects_seed.sql');

function sql(value: string): string {
	return "'" + value.replace(/'/g, "''") + "'";
}
function flag(value: boolean | undefined): number {
	return value ? 1 : 0;
}
function parseProjects(locale: 'es' | 'en'): Project[] {
	const raw = fs.readFileSync(path.join(source, `projects.${locale}.toml`), 'utf8');
	const data = parse(raw) as ProjectsData;
	if (!Array.isArray(data.projects) || data.projects.length === 0) {
		throw new Error(`No projects found in projects.${locale}.toml`);
	}
	const seen = new Set<string>();
	for (const project of data.projects) {
		if (!project.slug || seen.has(project.slug)) {
			throw new Error(`Missing or duplicate project slug in ${locale}: ${project.slug}`);
		}
		seen.add(project.slug);
		if (!project.title || !project.summary || !Array.isArray(project.stack) ||
			!Array.isArray(project.skills) || !Array.isArray(project.highlights)) {
			throw new Error(`Invalid project record: ${project.slug} (${locale})`);
		}
	}
	return data.projects;
}

const es = parseProjects('es');
const en = parseProjects('en');
const bySlug = (items: Project[]) => new Map(items.map((item) => [item.slug, item]));
if (es.length !== en.length || es.some((project) => !bySlug(en).has(project.slug))) {
	throw new Error('Spanish and English project files must contain the same slugs.');
}
const english = bySlug(en);
for (const project of es) {
	const other = english.get(project.slug)!;
	if (
		project.area !== other.area ||
		project.year !== other.year ||
		JSON.stringify(project.stack) !== JSON.stringify(other.stack) ||
		JSON.stringify(project.skills) !== JSON.stringify(other.skills)
	) {
		throw new Error(`Neutral project fields differ between locales: ${project.slug}`);
	}
}

const statements = es.map((project, index) => {
	const translated = english.get(project.slug)!;
	return `INSERT INTO portfolio_projects
  (slug, area, year, featured, status, sort_order, content_es, content_en, is_published)
VALUES
  (${sql(project.slug)}, ${sql(project.area)}, ${sql(project.year)}, ${flag(project.featured)},
   ${project.status ? sql(project.status) : 'NULL'}, ${index},
   ${sql(JSON.stringify(project))}, ${sql(JSON.stringify(translated))}, 1)
ON CONFLICT(slug) DO UPDATE SET
  area = excluded.area,
  year = excluded.year,
  featured = excluded.featured,
  status = excluded.status,
  sort_order = excluded.sort_order,
  content_es = excluded.content_es,
  content_en = excluded.content_en,
  updated_at = CURRENT_TIMESTAMP;`;
});

const content = `-- Generated by scripts/export-projects-d1.ts. Do not edit by hand.
-- Idempotent import of bilingual project content from the existing TOML files.
-- Review before applying. This file contains the current projects, not a runtime fallback.

${statements.join('\n\n')}
`;
fs.writeFileSync(output, content, 'utf8');
console.log(`Generated ${output} with ${es.length} bilingual projects.`);
